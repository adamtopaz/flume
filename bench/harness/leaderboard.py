#!/usr/bin/env python3
"""Regenerate research/results/LEADERBOARD.md from the result JSON files.

Usage: python3 bench/harness/leaderboard.py [--results DIR] [--out FILE]

Lists every committed run (newest first) with its suite, verdict, and the candidate's
speedups over flume `main`, stock Lake, and (when measured) Blake, plus a per-machine
"best so far" table of flume's speedup over Lake. A run counts for "best" when it is
standard, its candidate was correct, and its commit is reachable from `main`. Speedups
are geometric means over the corpora of a run; `overall` is the geometric mean of the
three workflows (single checkout, many checkouts, cold), each the geometric mean of
its scenarios. A workflow regenerates this file after every merge that adds results;
contributors do not commit it (render it locally with `--out bench/work/LEADERBOARD.md`).
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RESULTS = ROOT / "research" / "results"
KEY_SCENARIOS = ("noop", "leaf", "hub-interface", "swarm", "clone", "agents-4", "cold")
FLOWS = ("workflow:single", "workflow:many", "workflow:cold")


def fmt(x) -> str:
    return f"{x:.3f}x" if isinstance(x, (int, float)) else "-"


def load(results_dir: Path) -> list[dict]:
    runs = []
    for p in sorted(results_dir.glob("*.json")):
        try:
            r = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        if r.get("schema") != 3:
            continue
        r["_file"] = p.name
        runs.append(r)
    runs.sort(key=lambda r: r["timestamp"], reverse=True)
    return runs


def speed(r: dict, tool: str, base: str) -> dict:
    return r.get("speedup", {}).get(tool, {}).get(f"vs_{base}", {})


def correct(r: dict, tool: str) -> str:
    c = r.get("correctness", {}).get(tool)
    if not c:
        return "n/a"
    ok = all(v.get("identical") and v.get("builds_ok", True) and v.get("break_ok") is not False for v in c.values())
    return "yes" if ok else "**NO**"


def on_main(commit: str) -> bool:
    for ref in ("origin/main", "main"):
        p = subprocess.run(["git", "merge-base", "--is-ancestor", commit, ref], cwd=ROOT, capture_output=True)
        if p.returncode == 0:
            return True
    return False


def render(runs: list[dict]) -> str:
    out = ["# Leaderboard", "",
           "Generated by `bench/harness/leaderboard.py` (a workflow runs it after merges); do not edit by hand.",
           "Speedups are geometric means over a run's corpora of the baseline's median wall-clock divided by",
           "flume's. `overall` is the geometric mean of the three workflows. Runs on different machines are",
           "comparable only through these ratios.", ""]
    out += ["## Best flume vs stock Lake, per machine (standard runs of merged commits)", "",
            "| machine | cpus | suite | commit | label | date | overall | single | many | cold | "
            + " | ".join(KEY_SCENARIOS) + " |",
            "|---|---|---|---|---|---|---|---|---|---|" + "---|" * len(KEY_SCENARIOS)]
    best: dict[tuple[str, str], dict] = {}
    for r in runs:
        s = speed(r, "candidate", "lake")
        if "overall" not in s or correct(r, "candidate") != "yes" or not r.get("standard"):
            continue
        if not on_main(r["git"]["commit"]):
            continue
        k = (r["machine"]["id"], r.get("suite", "?"))
        if k not in best or s["overall"] > speed(best[k], "candidate", "lake")["overall"]:
            best[k] = r
    for (mid, suite), r in sorted(best.items()):
        s = speed(r, "candidate", "lake")
        out.append(f"| {mid} | {r['machine']['caps']['cpu_count']} | {suite} | {r['git']['commit'][:7]} | "
                   f"{r.get('label', '')} | {r['timestamp'][:10]} | **{fmt(s.get('overall'))}** | "
                   + " | ".join(fmt(s.get(f)) for f in FLOWS) + " | "
                   + " | ".join(fmt(s.get(k)) for k in KEY_SCENARIOS) + " |")
    if not best:
        out.append("| (no qualifying runs yet) |" + " |" * (9 + len(KEY_SCENARIOS)))
    out += ["", "## All committed runs (newest first)", "",
            "| date (UTC) | machine | cpus | suite | branch | commit | label | verdict | vs main | vs lake | vs blake | correct | standard | duration | file |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        dirty = "+" if r["git"].get("dirty") else ""
        tgt = f" ({','.join(r['targets'])})" if r.get("targets") else ""
        out.append(f"| {r['timestamp'][:16].replace('T', ' ')} | {r['machine']['id']} | {r['machine']['caps']['cpu_count']} | "
                   f"{r.get('suite', '?')} | {r['git']['branch']} | {r['git']['commit'][:7]}{dirty} | {r.get('label', '')} | "
                   f"{r.get('verdict', {}).get('overall', '-')}{tgt} | {fmt(speed(r, 'candidate', 'main').get('overall'))} | "
                   f"{fmt(speed(r, 'candidate', 'lake').get('overall'))} | {fmt(speed(r, 'candidate', 'blake').get('overall'))} | "
                   f"{correct(r, 'candidate')} | {'yes' if r.get('standard') else 'no'} | "
                   f"{int(r.get('duration_s', 0)) // 60} min | `{r['_file']}` |")
    out += ["", "## Per-scenario detail of the newest standard run per machine", ""]
    seen = set()
    for r in runs:
        mid = r["machine"]["id"]
        if mid in seen or not r.get("standard"):
            continue
        seen.add(mid)
        caps = r["machine"]["caps"]
        out.append(f"### {mid}: {r['machine']['cpu']} ({caps['cpu_count']} cpus, {caps['mem_gb']} GB cap), "
                   f"{r['timestamp'][:10]}, suite {r.get('suite')}, commit {r['git']['commit'][:7]}")
        out.append("")
        tools = [t for t in r["tool_order"] if t in next(iter(r["measurements"].values()), {})]
        out.append("| corpus | scenario | " + " | ".join(tools) + " |")
        out.append("|---|---|" + "---|" * len(tools))
        for cfg, per_tool in r["measurements"].items():
            keys: list[str] = []
            for t in tools:
                for k in per_tool.get(t, {}):
                    if isinstance(per_tool[t][k], dict) and "runs" in per_tool[t][k] and k not in keys:
                        keys.append(k)
            for k in keys:
                cells = []
                for t in tools:
                    m = per_tool.get(t, {}).get(k, {}).get("median_wall_s")
                    cells.append(f"{m:.2f} s" if m is not None else "-")
                out.append(f"| {cfg} | {k} | " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default=str(RESULTS))
    ap.add_argument("--out", default=str(RESULTS / "LEADERBOARD.md"))
    args = ap.parse_args()
    runs = load(Path(args.results))
    Path(args.out).write_text(render(runs), encoding="utf-8")
    print(f"wrote {args.out} ({len(runs)} runs)")


if __name__ == "__main__":
    main()
